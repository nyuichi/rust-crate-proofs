#!/usr/bin/env python3
from pathlib import Path
import subprocess,tempfile,hashlib,json
p=Path(__file__).resolve().parent
with tempfile.TemporaryDirectory() as t:
 out=Path(t)
 cmd=['charon','cargo','--preset','aeneas','--sysroot','default','--remove-unused-self-clauses','--dest',str(out),'--start-from','either::Either::copied','--start-from','either::Either::cloned']
 subprocess.run(cmd,cwd=p/'source',check=True)
 subprocess.run(['aeneas','-backend','lean','-emit-json','-filter-trait-methods','-abort-on-error','-dest',str(out/'generated'),str(out/'either.llbc')],check=True)
 assert (out/'generated/Either.lean').read_bytes()==(p/'generated/Either.lean').read_bytes()
 subprocess.run(['lake','build','ReferenceProofs'],cwd=p/'proofs',check=True)
 subprocess.run(['lake','env','lean','audit.lean'],cwd=p/'proofs',check=True)
 print('original extraction/generated byte equality/proof/audit PASS')
