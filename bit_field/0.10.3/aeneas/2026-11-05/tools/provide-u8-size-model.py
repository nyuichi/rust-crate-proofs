from pathlib import Path
import json,re
root=Path(__file__).resolve().parents[1]
j=json.loads((root/'evidence/bit_field.llbc').read_text())
assert not j['has_errors']
t=j['translated']
expected_u8={'Untagged':{'Scalar':{'Integer':{'Unsigned':'U8'}}}}
# Inspect every serialized function, not just generated declarations, so a new
# non-u8 size_of use cannot silently share this deliberately restricted model.
size_funs=[f for f in t['fun_decls'] if f and f['item_meta']['name']==[
 {'Ident':['core',0]},{'Ident':['mem',0]},{'Ident':['size_of',0]}]]
assert len(size_funs)==1
size_id=size_funs[0]['def_id']
size_calls=[]
def visit(n):
 if isinstance(n,dict):
  regular=n.get('Regular')
  if isinstance(regular,dict) and regular.get('kind')=={'Fun':size_id}:
   assert regular['generics']['types']==[expected_u8],regular
   size_calls.append(regular)
  for value in n.values():visit(value)
 elif isinstance(n,list):
  for value in n:visit(value)
visit(t['fun_decls'])
assert len(size_calls)==1,len(size_calls)
pr=root/'proofs/BitField'
# Pin the entire generated declaration set and all Lean external call sites.
manifest=json.loads((pr/'translation.json').read_text())
local=[f['lean_name'] for f in manifest['functions'] if f['is_local']]
assert set(local)=={'bit_field.U8.Insts.Bit_fieldBitField.get_bit',
 'bit_field.U8.Insts.Bit_fieldBitField.set_bit'},local
assert set(re.findall(r'^def ([^\s]+)',(pr/'Funs.lean').read_text(),re.M))=={
 'U8.Insts.Bit_fieldBitField.BIT_LENGTH','U8.Insts.Bit_fieldBitField.get_bit',
 'U8.Insts.Bit_fieldBitField.set_bit'}
applications=[]
for p in pr.glob('*.lean'):
 if p.name in {'FunsExternal.lean','FunsExternal_Template.lean'}:continue
 text=p.read_text()
 applications += re.findall(r'core\.mem\.size_of\s+([^\s\n]+)',text)
assert applications==['Std.U8'],applications
s=(pr/'FunsExternal_Template.lean').read_text()
needle='axiom core.mem.size_of (T : Type _) : Result Std.Usize'
assert s.count(needle)==1
s=s.replace('-- THIS FILE WAS AUTOMATICALLY GENERATED BY AENEAS',
 '-- Manual u8-only external model, based on the retained official Aeneas template.')
s=s.replace('@[rust_fun "core::mem::size_of"]\n'+needle,'''/- This is a manually supplied, executable model ONLY for the one
    size_of::<u8>() call in the guarded extracted program. The generic signature
    comes from Aeneas; it does NOT model size_of for arbitrary types. Do not reuse
    it for other instantiations. The guard above checks every serialized LLBC
    function and every generated Lean module and rejects non-U8 applications.
    Kani independently checks Rust size_of::<u8>() = 1 on x86_64. -/
@[rust_fun "core::mem::size_of"]
def core.mem.size_of (_T : Type _) : Result Std.Usize := .ok 1#usize''')
(pr/'FunsExternal.lean').write_text(s)
print('Guard passed: sole size_of application is U8; only U8 get/set/length translated')
